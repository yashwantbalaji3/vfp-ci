// Writes .env.local from the running LOCAL Supabase stack (never a hosted project).
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { randomBytes } from "node:crypto";

const raw = execFileSync("./node_modules/.bin/supabase", ["status", "-o", "json"], {
  encoding: "utf8",
  stdio: ["ignore", "pipe", "ignore"],
});
const status = JSON.parse(raw.slice(raw.indexOf("{")));
const apiUrl = status.API_URL;
if (!/^http:\/\/(127\.0\.0\.1|localhost):/.test(apiUrl)) {
  throw new Error(`Refusing to write env for a non-local Supabase URL: ${apiUrl}`);
}
// Keyed-hash salt for the rate limiter. Random per machine, kept across rewrites, never committed.
const previous = existsSync(".env.local") ? readFileSync(".env.local", "utf8").match(/^RATE_LIMIT_SALT=(.+)$/m)?.[1] : undefined;
const rateLimitSalt = previous ?? randomBytes(24).toString("hex");
const streetMap = ["local-maps/boston.pmtiles", "tests/fixtures/maps/central-square.pmtiles"].find((f) => existsSync(f));
const lines = [
  "# Generated by scripts/write-local-env.mjs for LOCAL development only.",
  'NEXT_PUBLIC_APP_NAME="Vegetarian Food Platform"',
  "NEXT_PUBLIC_APP_URL=http://localhost:3000",
  `NEXT_PUBLIC_SUPABASE_URL=${apiUrl}`,
  `NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${status.PUBLISHABLE_KEY}`,
  "DEFAULT_MARKET=boston",
  "PUBLIC_RELEASE_ENABLED=false",
  // Local testing only: lets a signed-out visitor open a published list or profile, so that
  // journey can be tested. The hosted default stays false until the owner approves it.
  "SOCIAL_PUBLIC_ENABLED=true",
  "ALLOW_DEMO_CONTENT=true",
  // Local testing only: Map Discovery (MAP-1, synthetic data). Unset (the hosted default) hides it.
  "MAP_ENABLED=true",
  // Local only: the founder's private preview of real places (docs/32). Unset (the hosted default) hides it.
  "REAL_CATALOG_PREVIEW=true",
  // Local only: restaurant submissions (docs/48). Unset (the hosted default) hides every partner page.
  "PARTNER_SUBMISSIONS=true",
  // Local only: the street-map file (MAP-1.1, docs/21). The full Boston file is kept out of git in
  // local-maps/; without it the small committed test map is used; without either, the plain background.
  ...(streetMap ? [`MAP_STREET_FILE=${streetMap}`] : []),
  `SUPABASE_SECRET_KEY=${status.SECRET_KEY}`,
  `DATABASE_URL=${status.DB_URL}`,
  `RATE_LIMIT_SALT=${rateLimitSalt}`,
  // Proof that a rate-limit hit comes from this server. Fixed for LOCAL use only; its digest is
  // registered by supabase/seed.sql. A hosted environment gets its own random secret.
  "RATE_LIMIT_KEY=local-development-only-rate-limit-key-0000",
  // Which request header carries the visitor's address. Locally there is no hosting layer, so
  // the tests supply x-forwarded-for themselves. When hosted this names the one header the host
  // guarantees (decided at R4); if it is unset, every visitor shares one allowance.
  "TRUSTED_ADDRESS_HEADER=x-forwarded-for",
  // Local testing only: the browser tests sign the same few people in many times a minute.
  // Unset (the hosted default) means the strict sign-in limits apply.
  "SIGNIN_LIMIT_SCALE=200",
  // Local testing only: enables /health/fault, a page that fails on purpose to test the error screen.
  "ALLOW_FAULT_TEST=true",
  `MAILPIT_URL=${status.MAILPIT_URL ?? "http://127.0.0.1:54324"}`,
];
writeFileSync(".env.local", lines.join("\n") + "\n");
console.log("Wrote .env.local for the local Supabase stack.");
