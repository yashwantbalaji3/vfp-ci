// Builds supabase/demo-topup.sql from a FRESHLY SEEDED local database. LOCAL ONLY.
//
//   pnpm exec supabase db reset        (disposable database only: this erases it)
//   node scripts/make-demo-topup.mjs
//
// The output lets an older local database gain the demo rows that supabase/seed.sql added in
// later milestones without a reset: it only ever adds rows that are missing (docs/22 section 3).
// Run this again whenever supabase/seed.sql changes; tests/unit/demo-topup.test.ts checks that.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const CONTAINER = "supabase_db_vegetarian-food-platform";
// Merge order respects foreign keys. Rows of tables marked `rev` belong to one catalog revision
// and are only added together with a revision that is itself new (published evidence is frozen).
const TABLES = [
  ["app.freshness_rules"], ["app.platform_switches"], ["app.server_keys"], ["auth.users"],
  ["public.markets"], ["public.licenses"], ["public.sources"], ["public.source_records"],
  ["public.nutrient_definitions"], ["public.ingredient_families"], ["public.geo_areas"], ["public.venues"],
  ["public.food_items", "items"], ["public.food_revisions", "revisions"],
  ["public.portions", "rev"], ["public.nutrient_values", "rev"], ["public.dietary_claims", "rev"],
  ["public.allergen_statements", "rev"], ["public.ingredient_family_statements", "rev"],
  ["public.recipe_revisions", "rev"], ["public.recipe_ingredients", "rev"], ["public.recipe_steps", "rev"],
  ["public.dishes"],
  // MAP-2 opening hours: only for places that have no checked hours yet; a set's rows are written
  // before the set is sealed, as app.publish_hours does.
  ["public.venue_hours_sets", "hours", "", "r.id in (select id from new_hour_sets)"],
  ["public.venue_hours_intervals", "", "", "r.set_id in (select id from new_hour_sets)"],
  ["public.venue_hours_exceptions", "", "", "r.set_id in (select id from new_hour_sets)"],
  // Prices have random ids, so an older database already holding a price for a dish keeps it.
  ["public.dish_prices", "", "", "not exists (select 1 from public.dish_prices d where d.dish_id = r.dish_id)"],
  ["public.profiles_public"], ["public.member_standing"], ["public.role_assignments"], ["public.follows"],
  // Reviews and published rankings also have random ids: a member's existing review of the same
  // place or dish, or an existing published ranking, is kept and not added again.
  ["public.reviews", "", "", "r.id in (select id from new_reviews)"],
  ["public.review_revisions", "", "", "r.review_id in (select id from new_reviews)"],
  ["public.ranking_entries", "", "(owner_id, venue_id)", "not exists (select 1 from public.ranking_entries e where e.owner_id = r.owner_id)"],
  ["public.ranking_publications", "", "", "not exists (select 1 from public.ranking_publications p where p.owner_id = r.owner_id)"],
  ["public.food_lists"],
  ["public.food_list_items", "", "(id)", "r.list_id in (select id from new_lists)"],
];
const ANCHOR = "00000000-0000-4000-8000-00000000b201"; // the seed's demo source record, stamped now()
const ref = (t) => `pg_temp.ref_${t.replace(".", "_")}`;

const dump = execFileSync(
  "docker",
  ["exec", CONTAINER, "pg_dump", "-U", "postgres", "-d", "postgres", "--data-only", "--column-inserts", ...TABLES.flatMap(([t]) => ["-t", t])],
  { encoding: "utf8", maxBuffer: 64 * 1024 * 1024, stdio: ["ignore", "pipe", "ignore"] },
);
const inserts = dump.split("\n").filter((l) => l.startsWith("INSERT INTO "));
const columns = new Map();
const rows = [];
for (const line of inserts) {
  const m = line.match(/^INSERT INTO ([a-z_]+\.[a-z_]+) \(([^)]*)\) VALUES /);
  if (!m || !TABLES.some(([t]) => t === m[1])) throw new Error(`unexpected dump line: ${line.slice(0, 80)}`);
  columns.set(m[1], m[2]);
  rows.push(line.replace(`INSERT INTO ${m[1]} `, `INSERT INTO ${ref(m[1])} `));
}
const missing = TABLES.filter(([t]) => !columns.has(t)).map(([t]) => t);
if (missing.length) throw new Error(`no rows dumped for ${missing.join(", ")}: is the database freshly seeded?`);

const seedHash = createHash("sha256").update(readFileSync("supabase/seed.sql")).digest("hex");
const revOf = (alias) =>
  `coalesce(to_jsonb(${alias}) ->> 'revision_id', to_jsonb(${alias}) ->> 'recipe_revision_id', to_jsonb(${alias}) ->> 'food_revision_id')::uuid`;

const out = [];
out.push(
  `-- GENERATED by scripts/make-demo-topup.mjs. Do not edit by hand. LOCAL DEVELOPMENT ONLY.`,
  `-- seed.sql sha256: ${seedHash}`,
  `--`,
  `-- Adds the synthetic demo rows of supabase/seed.sql that an older local database is missing,`,
  `-- including the local development request-counter key. It only INSERTs missing rows:`,
  `--   * nothing is deleted, and no existing row is changed, except that the local-only`,
  `--     "social_public" demo switch is turned on, exactly as seed.sql does;`,
  `--   * evidence of an already published catalog revision is never touched (it is frozen);`,
  `--   * everything runs in one transaction: if any step fails, nothing at all is changed;`,
  `--   * running it twice adds nothing the second time.`,
  `-- Apply it with: pnpm local:doctor --add-missing-demo   (refuses any database not on this computer)`,
  `begin;`,
);
for (const [t] of TABLES) out.push(`create temp table ${ref(t).slice(8)} (like ${t}) on commit drop;`);
out.push(...rows);
// seed.sql stamps its rows with the time it runs ("checked today", "expires in 60 days"). Move
// every date and time in the staged rows forward by the age of this file, so the added rows read
// as if seed.sql had run just now. Only the staged copies are changed, never an existing row.
out.push(
  `do $$`,
  `declare shift interval; c record;`,
  `begin`,
  `  select now() - observed_at into strict shift from ${ref("public.source_records")} where id = '${ANCHOR}';`,
  `  for c in select cl.relname, a.attname, format_type(a.atttypid, a.atttypmod) as typ`,
  `             from pg_attribute a join pg_class cl on cl.oid = a.attrelid`,
  `            where cl.relnamespace = pg_my_temp_schema() and cl.relname like 'ref\\_%' and a.attnum > 0 and not a.attisdropped`,
  `              and a.atttypid in ('timestamptz'::regtype, 'date'::regtype) loop`,
  `    execute format('update pg_temp.%I set %I = (%I + %L::interval)::%s', c.relname, c.attname, c.attname, shift, c.typ);`,
  `  end loop;`,
  `end $$;`,
);
out.push(
  `create temp table topup_report (tbl text, added int) on commit drop;`,
  `create temp table new_items on commit drop as select id from ${ref("public.food_items")} where id not in (select id from public.food_items);`,
  `create temp table new_revisions on commit drop as select id from ${ref("public.food_revisions")} where id not in (select id from public.food_revisions);`,
  `create temp table new_hour_sets on commit drop as select id from ${ref("public.venue_hours_sets")} r where r.state = 'published' and not exists (select 1 from public.venue_hours_sets x where x.venue_id = r.venue_id);`,
  `create temp table new_lists on commit drop as select id from ${ref("public.food_lists")} where id not in (select id from public.food_lists);`,
  `create temp table new_reviews on commit drop as select id from ${ref("public.reviews")} r where not exists (select 1 from public.reviews x where x.author_id = r.author_id and (x.venue_id = r.venue_id or x.food_item_id = r.food_item_id));`,
);
// Two tables keep list positions unique only at commit time (a deferred check), which
// "on conflict do nothing" cannot use, so they name their primary key instead.
for (const [t, kind, target = "", skipUnless] of TABLES) {
  const cols = columns.get(t);
  let select = `select ${cols} from ${ref(t)} r`;
  if (kind === "items") select = `select ${cols.replace("current_revision_id", "null").replace(/\bstatus\b/, "'draft'")} from ${ref(t)} r where r.id in (select id from new_items)`;
  if (kind === "hours") select = `select ${cols.replace(/\bsealed\b/, "false")} from ${ref(t)} r`;
  if (kind === "revisions") select = `select ${cols.replace("published_at", "null")} from ${ref(t)} r where r.id in (select id from new_revisions)`;
  if (kind === "rev") select += ` where ${revOf("r")} in (select id from new_revisions)`;
  if (skipUnless) select += ` where ${skipUnless}`;
  out.push(
    `with added as (insert into ${t} (${cols}) ${select} on conflict ${target}${target ? " " : ""}do nothing returning 1) insert into topup_report select '${t}', count(*) from added;`,
  );
  if (t === "public.venue_hours_exceptions") {
    out.push(`update public.venue_hours_sets set sealed = true where id in (select id from new_hour_sets);`);
  }
  if (kind === "rev" && t === "public.recipe_steps") {
    // Publish the new revisions only after their evidence is in place, as seed.sql does.
    out.push(
      `update public.food_revisions f set published_at = r.published_at from ${ref("public.food_revisions")} r where f.id = r.id and f.id in (select id from new_revisions);`,
      `update public.food_items f set current_revision_id = r.current_revision_id, status = r.status from ${ref("public.food_items")} r where f.id = r.id and f.id in (select id from new_items);`,
    );
  }
}
out.push(
  `update app.platform_switches set enabled = true, updated_at = now() where name = 'social_public' and not enabled;`,
  `select tbl as "table", added as "rows added" from topup_report where added > 0 order by tbl;`,
  `select coalesce(sum(added), 0) as "total rows added" from topup_report;`,
  `commit;`,
  ``,
);
writeFileSync("supabase/demo-topup.sql", out.join("\n"));
console.log(`wrote supabase/demo-topup.sql: ${rows.length} reference rows from ${TABLES.length} tables`);
